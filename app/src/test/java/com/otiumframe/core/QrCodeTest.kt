 * 각 버전의 용량을 정확히 채우는 길이(17/32/53/78 바이트)를 쓴다 — segno 는 패드 코드워드 앞에 0 바이트를 하나 더 넣는 버그가 있어
 * 패딩이 생기는 길이로는 비교할 수 없다. 패딩은 [padsPerSpec] 가 규격 값으로 직접 확인한다.
 */
