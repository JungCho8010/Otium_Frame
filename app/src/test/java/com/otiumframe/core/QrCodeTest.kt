    @Test
    fun formatBitsForLevelLMask0() {
        assertEquals(0x77C4, QrCode.formatBits())
    }

    @Test
    fun padsPerSpec() {
        // 30 바이트 → 12+240 비트 + 종료 4비트 = 32 바이트, 남은 2 바이트는 0xEC, 0x11
        val data = QrCode.dataCodewords("http://10.0.2.16:8787/a1b2c3d4".toByteArray(), 34)
        assertEquals(34, data.size)
        assertArrayEquals(byteArrayOf(0x40, 0xEC.toByte(), 0x11), data.copyOfRange(31, 34))
        // 19 바이트 → 버전 2(34): 종료 4 + 경계 패딩 4 + 패드 13 바이트
        val tail = QrCode.dataCodewords("http://10.0.2.16/ab".toByteArray(), 34).copyOfRange(21, 34)
        assertArrayEquals(ByteArray(13) { if (it % 2 == 0) 0xEC.toByte() else 0x11 }, tail)
    }

