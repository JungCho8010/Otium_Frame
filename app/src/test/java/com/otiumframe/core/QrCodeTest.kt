    fun rejectsOver78Bytes() {
        QrCode.encode("x".repeat(79))
    }

    private fun check(text: String, expected: String) {
        val actual = QrCode.encode(text).joinToString("\n") { row -> row.joinToString("") { if (it) "#" else "." } }
        assertEquals(expected.trimIndent().trim(), actual)
